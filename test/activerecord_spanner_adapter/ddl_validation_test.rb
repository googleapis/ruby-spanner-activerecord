# frozen_string_literal: true

require "test_helper"

class DdlValidationTest < TestHelper::MockActiveRecordTest
  def setup
    super
    @adapter = ActiveRecord::ConnectionAdapters::SpannerAdapter.new(
      connection, nil, nil, { project: project_id, instance: instance_id, database: database_id }
    )
  end

  def test_type_to_sql_validates_limit
    assert_equal "STRING(MAX)", @adapter.type_to_sql(:string)
    assert_equal "STRING(MAX)", @adapter.type_to_sql(:string, limit: nil)
    assert_equal "STRING(MAX)", @adapter.type_to_sql(:string, limit: "max")
    assert_equal "STRING(MAX)", @adapter.type_to_sql(:string, limit: "MAX")
    assert_equal "STRING(MAX)", @adapter.type_to_sql(:string, limit: "Max")
    assert_equal "STRING(MAX)", @adapter.type_to_sql(:text, limit: :max)
    assert_equal "STRING(256)", @adapter.type_to_sql(:text, limit: 256)
    assert_equal "STRING(128)", @adapter.type_to_sql(:string, limit: 128)
    assert_equal "BYTES(64)", @adapter.type_to_sql(:binary, limit: "64")
    assert_equal "ARRAY<STRING(128)>", @adapter.type_to_sql(:string, limit: 128, array: true)
    assert_equal "ARRAY<BYTES(MAX)>", @adapter.type_to_sql(:binary, array: true)

    [
      0,
      -1,
      12.5,
      true,
      false,
      "",
      "0",
      "01",
      "+64",
      "-5",
      " 64 ",
      "MAX ",
      "MAX)",
      "128\n",
      "10); DROP TABLE users; --"
    ].each do |invalid_limit|
      [:string, :text, :binary].each do |type|
        assert_raises(ArgumentError, "Expected ArgumentError for #{type} limit #{invalid_limit.inspect}") do
          @adapter.type_to_sql type, limit: invalid_limit
        end
      end
    end
  end

  def test_schema_creation_validates_allow_commit_timestamp
    schema_creation = ActiveRecord::ConnectionAdapters::Spanner::SchemaCreation.new @adapter

    [true, false].each do |valid_value|
      td = build_table_definition
      td.datetime :created_at, allow_commit_timestamp: valid_value
      assert_includes schema_creation.accept(td), "OPTIONS (allow_commit_timestamp = #{valid_value})"
    end

    td_nil = build_table_definition
    td_nil.datetime :created_at, allow_commit_timestamp: nil
    refute_includes schema_creation.accept(td_nil), "allow_commit_timestamp"

    td_non_timestamp = build_table_definition
    td_non_timestamp.string :name, allow_commit_timestamp: "bad"
    refute_includes schema_creation.accept(td_non_timestamp), "allow_commit_timestamp"

    [0, 1, "", :true, "true", "true); DROP TABLE events; --"].each do |invalid_value|
      td = build_table_definition
      td.datetime :created_at, allow_commit_timestamp: invalid_value
      assert_raises(ArgumentError, "Expected ArgumentError for #{invalid_value.inspect}") do
        schema_creation.accept td
      end
    end
  end

  def test_schema_creation_validates_sequence_kind
    schema_creation = ActiveRecord::ConnectionAdapters::Spanner::SchemaCreation.new @adapter

    ["BIT_REVERSED_POSITIVE", :BIT_REVERSED_POSITIVE, "_CUSTOM_KIND_2", "A"].each do |valid_kind|
      @adapter.default_sequence_kind = valid_kind
      td = build_table_definition
      td.primary_key :id
      assert_includes schema_creation.accept(td), "GENERATED BY DEFAULT AS IDENTITY (#{valid_kind})"
    end

    [
      "",
      " ",
      123,
      "1_INVALID",
      "INVALID-KIND",
      "INVALID`KIND",
      "BIT_REVERSED_POSITIVE\n",
      "BIT_REVERSED_POSÍTIVE",
      "BIT_REVERSED_POSITIVE); DROP TABLE events; --"
    ].each do |invalid_kind|
      @adapter.default_sequence_kind = invalid_kind
      td = build_table_definition
      td.primary_key :id
      assert_raises(ArgumentError, "Expected ArgumentError for #{invalid_kind.inspect}") do
        schema_creation.accept td
      end
    end
  end

  def test_schema_creation_handles_non_identity_sequence_modes
    schema_creation = ActiveRecord::ConnectionAdapters::Spanner::SchemaCreation.new @adapter

    [nil, false, "DISABLED", "disabled"].each do |disabled_kind|
      configured_adapter = ActiveRecord::ConnectionAdapters::SpannerAdapter.new(
        connection, nil, nil,
        { project: project_id, instance: instance_id, database: database_id,
          default_sequence_kind: disabled_kind }
      )
      assert_equal false, configured_adapter.use_identity?
      configured_schema_creation = ActiveRecord::ConnectionAdapters::Spanner::SchemaCreation.new configured_adapter
      td = build_table_definition configured_adapter
      td.primary_key :id
      sql = configured_schema_creation.accept td
      refute_includes sql, "GENERATED BY DEFAULT AS IDENTITY"
      refute_includes sql, "AUTO_INCREMENT"
    end

    ["AUTO_INCREMENT", "auto_increment"].each do |auto_increment_kind|
      @adapter.default_sequence_kind = auto_increment_kind
      assert_equal false, @adapter.use_identity?
      assert_equal true, @adapter.use_auto_increment?
      td = build_table_definition
      td.primary_key :id
      sql = schema_creation.accept td
      assert_includes sql, "AUTO_INCREMENT"
      refute_includes sql, "GENERATED BY DEFAULT AS IDENTITY"
    end

    @adapter.default_sequence_kind = "BIT_REVERSED_POSITIVE); DROP TABLE events; --"
    td_default_pk = build_table_definition
    td_default_pk.primary_key :id, default: -> { "GENERATE_UUID()" }
    default_pk_sql = schema_creation.accept td_default_pk
    assert_includes default_pk_sql, "DEFAULT (GENERATE_UUID())"
    refute_includes default_pk_sql, "GENERATED BY DEFAULT AS IDENTITY"

    td_non_pk = build_table_definition
    td_non_pk.integer :count
    non_pk_sql = schema_creation.accept td_non_pk
    assert_includes non_pk_sql, "`count` INT64"
    refute_includes non_pk_sql, "GENERATED BY DEFAULT AS IDENTITY"
  end

  def test_adapter_initialize_and_create_table_reject_invalid_ddl_options
    configured_adapter = ActiveRecord::ConnectionAdapters::SpannerAdapter.new(
      connection, nil, nil,
      { project: project_id, instance: instance_id, database: database_id,
        default_sequence_kind: 123 }
    )
    assert_raises ArgumentError do
      configured_adapter.create_table("events") { |t| t.string :name }
    end

    assert_raises ArgumentError do
      @adapter.create_table("events") { |t| t.string :name, limit: "10); DROP TABLE events; --" }
    end
    assert_raises ArgumentError do
      @adapter.add_column "events", :occurred_at, :datetime, allow_commit_timestamp: "true"
    end
    assert_raises ArgumentError do
      @adapter.add_column "events", :title, :string, limit: -1
    end
    assert_empty Array(last_executed_sqls)
  end

  private

  def build_table_definition adapter = @adapter
    ActiveRecord::ConnectionAdapters::Spanner::TableDefinition.new adapter, "events", options: {}
  end
end
